import * as yaml from 'js-yaml';
import { TaskPack, intentLabel } from './taskPack';

export interface RenderTaskPackOptions {
  includeAgentInstructions?: boolean;
}

export function renderTaskPackMarkdown(pack: TaskPack, options: RenderTaskPackOptions = {}): string {
  const lines: string[] = [
    `# Task Pack: ${pack.title}`,
    '',
    `Intent: ${intentLabel(pack.intent)}`,
    '',
    '## Goal',
    '',
    pack.goal || 'Describe the desired outcome before starting.',
    '',
  ];

  appendList(lines, 'Constraints', pack.constraints);
  appendContext(lines, pack);
  appendList(lines, 'Acceptance Criteria', pack.acceptanceCriteria);
  appendVerification(lines, pack.verificationCommands);

  if (options.includeAgentInstructions ?? true) {
    lines.push(
      '## Agent Instructions',
      '',
      '- Restate the plan briefly before making broad changes.',
      '- Prefer small, reviewable edits over speculative rewrites.',
      '- Run the verification commands when possible.',
      '- If verification cannot run, explain the blocker and the residual risk.',
      ''
    );
  }

  lines.push(
    '---',
    '',
    `Generated by Prompt by Prompt on ${pack.updatedAt}.`,
    ''
  );

  return compactBlankLines(lines).join('\n');
}

export function renderPromptFile(pack: TaskPack): string {
  const frontmatter = yaml.dump({
    description: `Run task pack: ${pack.title}`,
    agent: 'agent',
    'argument-hint': 'Add any final constraints or target files',
  }, {
    lineWidth: -1,
    noRefs: true,
    quotingType: '"',
  }).trim();

  return [
    '---',
    frontmatter,
    '---',
    '',
    renderTaskPackMarkdown(pack),
  ].join('\n');
}

