function appendContext(lines: string[], pack: TaskPack): void {
  lines.push('## Context', '');

  if (pack.contextItems.length === 0) {
    lines.push('- No context attached yet.', '');
    return;
  }

  for (const item of pack.contextItems) {
    lines.push(`### ${item.label}`, '');
    lines.push(`- Kind: ${item.kind}`);
    if (item.source) {
      lines.push(`- Source: ${item.source}`);
    }
    if (item.summary) {
      lines.push(`- Note: ${item.summary}`);
    }
    if (item.truncated) {
      lines.push(`- Truncated from ${item.charCount} characters`);
    }
    lines.push('');

    if (item.content?.trim()) {
      lines.push(`\`\`\`${item.language ?? ''}`.trimEnd());
      lines.push(item.content.trimEnd());
      lines.push('```', '');
    }
  }
}

function appendList(lines: string[], title: string, values: string[]): void {
  lines.push(`## ${title}`, '');
  if (values.length === 0) {
    lines.push('- None specified.', '');
    return;
  }

  for (const value of values) {
    lines.push(`- ${value}`);
  }
  lines.push('');
}

function appendVerification(lines: string[], commands: string[]): void {
  lines.push('## Verification', '');
  if (commands.length === 0) {
    lines.push('- Run the smallest relevant project checks and report what passed.', '');
    return;
  }

  for (const command of commands) {
    lines.push(`- \`${command}\``);
  }
  lines.push('');
}

function compactBlankLines(lines: string[]): string[] {
  const compacted: string[] = [];
  for (const line of lines) {
    if (line || compacted[compacted.length - 1] !== '') {
      compacted.push(line);
    }
  }
  return compacted;
}
